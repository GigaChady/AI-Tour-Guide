def get_nearby(lat: float, lon: float, radius_km: float = 50) -> list[dict]:
    import math

    def haversine(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
        r = 6371
        phi1, phi2 = math.radians(lat1), math.radians(lat2)
        dphi = math.radians(lat2 - lat1)
        dlambda = math.radians(lon2 - lon1)
        a = math.sin(dphi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlambda / 2) ** 2
        return 2 * r * math.asin(math.sqrt(a))

    return [
        loc for loc in TOURIST_LOCATIONS
        if haversine(lat, lon, loc["lat"], loc["lon"]) <= radius_km
    ]


def search_locations(query: str) -> list[dict]:
    q = query.lower()
    return [
        loc for loc in TOURIST_LOCATIONS
        if q in loc["name"].lower()
        or q in loc["city"].lower()
        or q in loc["country"].lower()
        or q in loc["description"].lower()
        or any(q in tag for tag in loc["tags"])
    ]
